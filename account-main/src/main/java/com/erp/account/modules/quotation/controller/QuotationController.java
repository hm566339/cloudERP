package com.erp.account.modules.quotation.controller;

import com.erp.account.modules.quotation.dto.request.QuotationCreateRequest;
import com.erp.account.modules.quotation.dto.request.QuotationFilterDto;
import com.erp.account.modules.quotation.dto.request.QuotationUpdateRequest;
import com.erp.account.modules.quotation.dto.response.QuotationResponse;
import com.erp.account.modules.quotation.dto.response.profile.QuotationProfileResponse;
import com.erp.account.modules.quotation.entity.QuotationStatus;
import com.erp.account.modules.quotation.service.QuotationService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.UUID;

@RestController
@RequestMapping({"/api/account/v1/quotations", "/api/account/sales/quotations"})
@RequiredArgsConstructor
@Tag(name = "Quotation API", description = "Quotation management with strict lifecycle rules")
public class QuotationController {

    private final QuotationService quotationService;
    private final com.erp.account.modules.quotation.service.QuotationPdfService quotationPdfService;

    @Operation(summary = "Create Quotation", description = "Creates a new DRAFT quotation. Quotation number is generated by the backend sequence.")
    @PostMapping
    public ResponseEntity<QuotationResponse> createQuotation(
            @RequestParam(required = false) UUID companyId,
            @Valid @RequestBody QuotationCreateRequest request) {
        return new ResponseEntity<>(quotationService.createQuotation(companyId, request), HttpStatus.CREATED);
    }

    @Operation(summary = "Get Quotation by ID")
    @GetMapping("/{id}")
    public ResponseEntity<QuotationProfileResponse> getQuotationById(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.getQuotationById(companyId, id));
    }

    @Operation(summary = "Get Quotation by Number")
    @GetMapping("/number/{quotationNumber}")
    public ResponseEntity<QuotationProfileResponse> getQuotationByNumber(
            @PathVariable String quotationNumber,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.getQuotationByNumber(companyId, quotationNumber));
    }

    @Operation(summary = "Get All Quotations")
    @GetMapping
    public ResponseEntity<Page<QuotationResponse>> getAllQuotations(
            @RequestParam(required = false) UUID companyId,
            QuotationFilterDto filter,
            Pageable pageable) {
        return ResponseEntity.ok(quotationService.getAllQuotations(companyId, filter, pageable));
    }

    @Operation(summary = "Update Quotation", description = "Only DRAFT quotations can be edited. Commercial fields recalculate on the backend.")
    @PutMapping("/{id}")
    public ResponseEntity<QuotationResponse> updateQuotation(
            @PathVariable UUID id,
            @Valid @RequestBody QuotationUpdateRequest request,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.updateQuotation(companyId, id, request));
    }

    @Operation(summary = "Delete Quotation", description = "Soft deletes a quotation. Only DRAFT quotations can be deleted.")
    @DeleteMapping("/{id}")
    public ResponseEntity<Void> deleteQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        quotationService.deleteQuotation(companyId, id);
        return ResponseEntity.noContent().build();
    }

    @Operation(summary = "Change Quotation Status", description = "Generic endpoint for state transitions. Strictly validated.")
    @PostMapping("/{id}/status")
    public ResponseEntity<QuotationResponse> changeStatus(
            @PathVariable UUID id,
            @RequestParam QuotationStatus status,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.changeStatus(companyId, id, status));
    }

    @Operation(summary = "Approve Quotation", description = "Internal approval. Transitions DRAFT to SENT.")
    @PostMapping("/{id}/approve")
    public ResponseEntity<QuotationResponse> approveQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.approveQuotation(companyId, id));
    }

    @Operation(summary = "Send Quotation", description = "Marks quotation as SENT to customer.")
    @PostMapping("/{id}/send")
    public ResponseEntity<QuotationResponse> sendQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.sendQuotation(companyId, id));
    }

    @Operation(summary = "Accept Quotation", description = "Customer accepts quotation. Transitions SENT to ACCEPTED. Locks quotation from edits.")
    @PostMapping("/{id}/accept")
    public ResponseEntity<QuotationResponse> acceptQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.acceptQuotation(companyId, id));
    }

    @Operation(summary = "Reject Quotation", description = "Customer rejects quotation. Transitions SENT to REJECTED. Terminal state.")
    @PostMapping("/{id}/reject")
    public ResponseEntity<QuotationResponse> rejectQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.rejectQuotation(companyId, id));
    }

    @Operation(summary = "Cancel Quotation", description = "Manually cancels quotation. Terminal state.")
    @PostMapping("/{id}/cancel")
    public ResponseEntity<QuotationResponse> cancelQuotation(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        return ResponseEntity.ok(quotationService.cancelQuotation(companyId, id));
    }

    @Operation(summary = "Download quotation PDF", description = "Generates and downloads the quotation PDF")
    @GetMapping(path = "/{id}/pdf")
    public void downloadQuotationPdf(
            @PathVariable("id") UUID quotationId,
            @RequestParam(required = false) UUID companyId,
            jakarta.servlet.http.HttpServletResponse response) {
        
        try {
            byte[] pdfBytes = quotationPdfService.generateQuotationPdf(quotationId, companyId);
            
            response.setContentType(org.springframework.http.MediaType.APPLICATION_PDF_VALUE);
            response.setHeader(org.springframework.http.HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"quotation-" + quotationId + ".pdf\"");
            response.setContentLength(pdfBytes.length);
            response.getOutputStream().write(pdfBytes);
            response.getOutputStream().flush();
        } catch (Exception ex) {
            throw new RuntimeException("Error generating Quotation PDF: " + ex.getMessage(), ex);
        }
    }
    @Operation(summary = "Resend Quotation Email", description = "Resend an existing quotation PDF to the customer's email without changing the quotation status.")
    @PostMapping("/{id}/send-email")
    public ResponseEntity<com.erp.account.common.dto.response.ApiResponse<com.erp.account.modules.quotation.dto.response.SendQuotationEmailResponse>> sendQuotationEmail(
            @PathVariable UUID id,
            @RequestParam(required = false) UUID companyId) {
        
        com.erp.account.modules.quotation.dto.response.SendQuotationEmailResponse data = quotationService.sendQuotationEmail(companyId, id);
        
        if ("FAILED".equals(data.getEmailStatus())) {
            return ResponseEntity.status(HttpStatus.INTERNAL_SERVER_ERROR)
                    .body(com.erp.account.common.dto.response.ApiResponse.error("Failed to send quotation email", data));
        }
        
        return ResponseEntity.ok(
                com.erp.account.common.dto.response.ApiResponse.success(data, "Quotation email sent successfully")
        );
    }

}
